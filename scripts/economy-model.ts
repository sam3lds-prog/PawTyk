/**
 * D51-B: prints the economy model (`src/meta/economyModel.ts`) for the three play patterns, from the game's real numbers.
 *
 *   npm run economy:model            # prints the tables
 *   npm run economy:model -- --write # also writes docs/economy-model.md's generated section
 *
 * It changes nothing in the game. The play patterns are assumptions until the beta's opt-in analytics replace them.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { SCENARIOS, gameCatalog, rulesSummary, runScenario, type EconomyResult } from '../src/meta/economyModel';
import { activityFor } from '../src/ui/art/activities';
import { OVERFLOW_COINS, STARTER_ITEMS } from '../src/meta/items';

const cat = gameCatalog((id) => !!activityFor(id));
const results = SCENARIOS.map((s) => runScenario(s, cat));

const n = (x: number | null) => (x === null ? 'never' : !Number.isFinite(x) ? 'never' : String(x));
const row = (label: string, f: (r: EconomyResult) => string | number) => `| ${label} | ${results.map((r) => String(f(r))).join(' | ')} |`;

const md = [
  '<!-- generated by `npm run economy:model -- --write`; edit scripts/economy-model.ts or src/meta/economyModel.ts, not this block -->',
  '',
  '### The rules it reads',
  '',
  '| Rule | Value |',
  '|---|---|',
  ...Object.entries(rulesSummary()).map(([k, v]) => `| ${k} | ${v} |`),
  `| Farm coin decorations (animals use) | ${cat.farmDecor.length} (${cat.farmDecor.filter((d) => d.interactive).length}) |`,
  `| Cheapest Farm piece the animals use | ${Math.min(...cat.farmDecor.filter((d) => d.interactive).map((d) => d.coins))} coins |`,
  `| Typical coin meal (median portion) | ${cat.typicalMeal} coins |`,
  `| Starter pantry (lives, hints) · overflow | ${STARTER_ITEMS.life}, ${STARTER_ITEMS.hint} · ${OVERFLOW_COINS} coins each over the cap |`,
  `| Video-token prices | ${Math.min(...cat.tokenPrices)}–${Math.max(...cat.tokenPrices)} |`,
  `| Gem prices | ${Math.min(...cat.gemPrices)}–${Math.max(...cat.gemPrices)} |`,
  '',
  '### Three play patterns',
  '',
  `| | ${results.map((r) => r.scenario.name).join(' | ')} |`,
  `|---|${results.map(() => '---').join('|')}|`,
  row('Sessions a day', (r) => r.scenario.sessionsPerDay),
  row('New levels a session', (r) => r.scenario.newLevelsPerSession),
  row('Daily solved (share of days)', (r) => r.scenario.dailyRate),
  row('Clean solves (share)', (r) => r.scenario.cleanRate),
  row('Errands finished a day (of 3)', (r) => r.scenario.errandsPerDay),
  row('Losses per 10 boards · extra life used', (r) => `${r.scenario.lossesPer10} · ${r.scenario.lifeUseRate}`),
  row('Paid hints per 10 boards', (r) => r.scenario.paidHintsPer10),
  row('Coin meals a day', (r) => r.scenario.mealsPerDay),
  row('Reward videos a day', (r) => r.scenario.videosPerDay),
  '',
  '### What that gives',
  '',
  `| | ${results.map((r) => r.scenario.name).join(' | ')} |`,
  `|---|${results.map(() => '---').join('|')}|`,
  row('Boards a day (Journey + Daily + Zen)', (r) => r.boards.total),
  row('**Paw Coins a day**', (r) => `**${r.coins.total}**`),
  row('… first clears', (r) => r.coins.firstClears),
  row('… clean bonuses', (r) => r.coins.clean),
  row('… Daily', (r) => r.coins.daily),
  row('… chapters', (r) => r.coins.chapters),
  row('… errands', (r) => r.coins.errands),
  row('… weekly errand', (r) => r.coins.weekly),
  row('… finished homes', (r) => r.coins.homes),
  row('Paw Coins a session', (r) => r.coinsPerSession),
  row('Pantry full in (days): lives · hints', (r) => `${n(r.pantry.livesFullInDays)} · ${n(r.pantry.hintsFullInDays)}`),
  row('Overflow once full (coins a day)', (r) => r.pantry.overflowPerDay),
  row('**Paw Coins a day once the pantry is full**', (r) => `**${r.pantry.coinsPerDayOnceFull}**`),
  row('Food a day (share of earnings)', (r) => `${r.food.perDay} (${Math.round(r.food.share * 100)}%)`),
  row('Days to the first Farm piece the animals use', (r) => n(r.daysTo.firstInteractiveFarmPiece)),
  row('Days to any Farm piece', (r) => n(r.daysTo.anyFarmPiece)),
  row('Days to every Farm coin decoration', (r) => n(r.daysTo.allFarmCoinDecor)),
  row('Days to every coin trick', (r) => n(r.daysTo.allCoinTricks)),
  row('Days to everything sold for coins', (r) => n(r.daysTo.everythingForCoins)),
  row('Extra lives a day: earned · used · net', (r) => `${r.lives.earned} · ${r.lives.used} · ${r.lives.net}`),
  row('Hints a day: earned · used · net', (r) => `${r.hints.earned} · ${r.hints.used} · ${r.hints.net}`),
  row('Days to the dearest video-token item', (r) => n(r.tokens.daysToDearest)),
  row('Levels in 30 days', (r) => r.levelsIn30Days),
  '',
  '<!-- end generated -->',
].join('\n');

console.log(md);
if (process.argv.includes('--write')) {
  const path = 'docs/economy-model.md';
  const doc = readFileSync(path, 'utf8');
  const start = doc.indexOf('<!-- generated by');
  const end = doc.indexOf('<!-- end generated -->');
  if (start < 0 || end < 0) throw new Error(`${path}: no generated block`);
  writeFileSync(path, doc.slice(0, start) + md + doc.slice(end + '<!-- end generated -->'.length));
  console.log(`\nWrote ${path}`);
}
